/**
 * 발주서 **커스텀 요청사항** — 커스텀 주문의 상세 요청.
 *
 * 예전엔 「별지(2페이지)」였다. 발주서를 A4 한 장에 맞추느라 비고 칸이 4줄뿐이라
 * 커스텀 내용을 담지 못했고, 그래서 장을 하나 더 냈다. 그런데 그 장도 한 장이라
 * 30줄·40자로 다시 묶어야 했고, **결국 분량이 계속 골칫거리**가 됐다(제보).
 *
 * 지금 발주서는 아래로 이어진다 — 길면 길어지는 대로 두고 보는 사람이 스크롤한다.
 * 그러니 **줄 수·글자 수를 정하지 않는다.** 다만 사람이 적는 글이 아닌 것이
 * 들어오는 것은 막아야 해서, 넉넉한 상한 하나만 남긴다.
 */

/**
 * 넉넉한 상한 — **양식 때문이 아니라 사고를 막으려고** 둔다.
 * 파일을 통째로 붙여 넣거나 API 로 수 MB 를 밀어 넣는 경우다.
 * 사람이 손으로 적는 요청사항은 이 근처에도 오지 않는다.
 */
export const APPENDIX_MAX_CHARS = 20_000;

/** 상한을 넘는 부분만 잘라 낸다. 줄바꿈·띄어쓰기는 적은 그대로 보관한다 */
export function clampAppendix(raw: string): string {
  return raw.replace(/\r\n?/g, '\n').slice(0, APPENDIX_MAX_CHARS);
}

/** 적힌 것이 있는가 — 공백만 있는 것은 비어 있는 것으로 본다 */
export function hasAppendix(v: string | null | undefined): boolean {
  return typeof v === 'string' && v.trim().length > 0;
}

